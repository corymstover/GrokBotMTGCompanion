#!/usr/bin/env python3
"""Build the per-card printing summary (issue #40, Bot cycle 10).

Card entries stay compact: printing history is kept in a separate index, not in the card shards.
  data/printings_summary.csv  one row per card entry (oracle_id) with printing counts and first/latest printing
  Printing History.md         field guide, distribution, and notable lists (most-reprinted, longest gaps,
                              single-printing staples, Reserved List)
Source: Scryfall default-cards bulk (every printing). A "printing" is a distinct (set, collector number).
Paper and digital-only printings are counted separately.
Usage: python3 scripts/build_printings.py && python3 scripts/resolve_card_links.py "Printing History.md"
"""
import csv
import gzip
import json
import sys
from collections import Counter, defaultdict
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CSV_OUT = ROOT / "data" / "printings_summary.csv"
MD_OUT = ROOT / "Printing History.md"


def d(s):
    return date.fromisoformat(s)


def main() -> int:
    index = {r["oracle_id"]: r for r in csv.DictReader((ROOT / "data" / "card_index.csv").open(encoding="utf-8"))}
    gz = sorted((ROOT / ".cache").glob("default-cards-*.jsonl.gz"))[-1]
    bulk_date = gz.name.split("-")[2][:8]
    pr = defaultdict(dict)  # oracle_id -> {(set, cn): printing}
    reserved = set()
    for ln in gzip.open(gz, "rt", encoding="utf-8"):
        c = json.loads(ln)
        o = c.get("oracle_id") or (c.get("card_faces") or [{}])[0].get("oracle_id")
        if o not in index:
            continue
        k = (c["set"], c["collector_number"])
        if k in pr[o] and c.get("lang") != "en":
            continue
        pr[o][k] = c
        if c.get("reserved"):
            reserved.add(o)
    rows = []
    for o, ps in pr.items():
        paper = sorted((p for p in ps.values() if not p.get("digital")), key=lambda p: (p["released_at"], p["set"]))
        digital = [p for p in ps.values() if p.get("digital")]
        if paper:
            f, l = paper[0], paper[-1]
            dates = sorted({p["released_at"] for p in paper})
            gaps = [(d(b) - d(a)).days for a, b in zip(dates, dates[1:])]
            gap = max(gaps) if gaps else 0
        else:
            allp = sorted(ps.values(), key=lambda p: p["released_at"])
            f, l, gap = allp[0], allp[-1], 0
        types = Counter(p["set_type"] for p in paper)
        rows.append({
            "name": index[o]["name"], "oracle_id": o,
            "paper_printings": len(paper), "paper_sets": len({p["set"] for p in paper}),
            "digital_only_printings": len(digital),
            "first_date": f["released_at"], "first_set": f["set"].upper(), "first_set_name": f["set_name"],
            "latest_date": l["released_at"], "latest_set": l["set"].upper(), "latest_set_name": l["set_name"],
            "longest_gap_days": gap, "reserved_list": int(o in reserved),
            "set_types": ";".join(f"{k}:{v}" for k, v in sorted(types.items())),
            "commander_legality": index[o]["commander_legality"], "edhrec_rank": index[o]["edhrec_rank"],
        })
    rows.sort(key=lambda r: r["name"].lower())
    with CSV_OUT.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    def link(r):
        return f"[[{r['name']}]]"

    def rk(r):
        return int(r["edhrec_rank"]) if r["edhrec_rank"] else 10**9

    dist = Counter()
    for r in rows:
        n = r["paper_printings"]
        dist["0 (digital only)" if n == 0 else "1" if n == 1 else "2–5" if n <= 5 else "6–10" if n <= 10 else "11–25" if n <= 25 else "26+"] += 1
    out = ["# Printing History", "",
           "> **Bot cycle 10 · issue [#40](https://github.com/corymstover/GrokBotMTGCompanion/issues/40).** Reprint and set history for every card entry, kept **outside** the card files so they stay compact. Look up any card in [`data/printings_summary.csv`](data/printings_summary.csv) (one row per card). This page explains the fields and lists the notable cases. Generated by `scripts/build_printings.py`.",
           f"> **Source:** Scryfall default-cards bulk ({bulk_date[:4]}-{bulk_date[4:6]}-{bulk_date[6:]}). A printing is a distinct set + collector number, so promos, variants and Secret Lair drops all count. Dates are Scryfall `released_at`. The **Reserved List** flag is Scryfall's `reserved` field (Wizards' [Official Reprint Policy](https://magic.wizards.com/en/news/announcements/official-reprint-policy)).",
           "", "## Contents",
           "- [Fields](#fields)", "- [Distribution](#distribution)", "- [Most-printed cards](#most-printed-cards)",
           "- [Longest gaps between paper printings](#longest-gaps-between-paper-printings)",
           "- [Popular Commander cards with a single paper printing](#popular-commander-cards-with-a-single-paper-printing)",
           "- [Reserved List](#reserved-list)", "",
           "## Fields", "| Column | Meaning |", "|---|---|",
           "| `paper_printings` · `paper_sets` | Distinct paper printings · distinct paper sets |",
           "| `digital_only_printings` | Printings that exist only on MTGO/Arena |",
           "| `first_*` · `latest_*` | Earliest and latest paper printing (date, set code, set name). Digital-only cards use their digital printings. Scryfall lists announced printings, so a `latest_date` can fall after the bulk date |",
           "| `longest_gap_days` | Longest stretch between two consecutive paper release dates |",
           "| `reserved_list` | 1 = on the Reserved List (Scryfall `reserved`) |",
           "| `set_types` | Paper printings by Scryfall set type (e.g. `expansion:3;commander:5`) |", "",
           "## Distribution", "| Paper printings | Cards |", "|---|---|"]
    for k in ["0 (digital only)", "1", "2–5", "6–10", "11–25", "26+"]:
        out.append(f"| {k} | {dist[k]:,} |")
    out += ["", f"Total: {len(rows):,} card entries · {sum(r['paper_printings'] for r in rows):,} paper printings.", "",
            "## Most-printed cards", "Top 40 by distinct paper sets (excluding basic lands).", "",
            "| Card | Paper sets | Printings | First | Latest |", "|---|---|---|---|---|"]
    nb = [r for r in rows if not index[r["oracle_id"]]["type_line"].startswith("Basic")]
    for r in sorted(nb, key=lambda r: (-r["paper_sets"], r["name"]))[:40]:
        out.append(f"| {link(r)} | {r['paper_sets']} | {r['paper_printings']} | {r['first_set']} ({r['first_date'][:4]}) | {r['latest_set']} ({r['latest_date'][:4]}) |")
    out += ["", "## Longest gaps between paper printings", "Top 30 Commander-legal cards by longest gap (in years) between two consecutive paper printings.", "",
            "| Card | Gap (years) | First | Latest | Paper printings |", "|---|---|---|---|---|"]
    leg = [r for r in rows if r["commander_legality"] == "legal"]
    for r in sorted(leg, key=lambda r: (-r["longest_gap_days"], r["name"]))[:30]:
        out.append(f"| {link(r)} | {r['longest_gap_days'] / 365.25:.1f} | {r['first_set']} ({r['first_date'][:4]}) | {r['latest_set']} ({r['latest_date'][:4]}) | {r['paper_printings']} |")
    out += ["", "## Popular Commander cards with a single paper printing", "The 40 best-ranked (EDHREC) Commander-legal cards with exactly one paper printing. They may be harder to find.", "",
            "| Card | EDHREC rank | Only printing |", "|---|---|---|"]
    for r in sorted([r for r in leg if r["paper_printings"] == 1 and r["edhrec_rank"]], key=rk)[:40]:
        out.append(f"| {link(r)} | {r['edhrec_rank']} | {r['first_set_name']} ({r['first_date']}) |")
    rl = sorted([r for r in rows if r["reserved_list"]], key=rk)
    out += ["", "## Reserved List", f"**{len(rl)} card entries** are flagged on the Reserved List. Per the [Official Reprint Policy](https://magic.wizards.com/en/news/announcements/official-reprint-policy): \"Reserved cards will never be printed again in a functionally identical form.\" These are the 30 best-ranked on EDHREC:", "",
            "| Card | EDHREC rank | Paper printings | First |", "|---|---|---|---|"]
    for r in rl[:30]:
        out.append(f"| {link(r)} | {r['edhrec_rank'] or '—'} | {r['paper_printings']} | {r['first_set_name']} ({r['first_date'][:4]}) |")
    MD_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{CSV_OUT.name}: {len(rows)} rows; reserved {len(rl)}; dist {dict(dist)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
