#!/usr/bin/env python3
"""Turn curated lore links into story beats; assemble user-curated 100-card EDH drafts.

  python3 scripts/story_deck_planner.py plan "Ugin vs Nicol Bolas"
  python3 scripts/story_deck_planner.py assemble draft.json
  python3 scripts/story_deck_planner.py assemble draft.json --validate

The plan is a *research outline*, not an autogenerated legal deck. The assembler
keeps story justifications and explicit playability slots; it only claims
Commander legality if evaluate_decklist.py succeeds against the frozen card
snapshot. All 62 approved Grixis lists are read-only and out of scope.
"""
import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import lore_query as Q

ORDER = ("ancient", "brothers", "postmending", "invasion", "omenpaths", "unplaced")
BASICS = {"Plains", "Island", "Swamp", "Mountain", "Forest", "Wastes",
          "Snow-Covered Plains", "Snow-Covered Island", "Snow-Covered Swamp",
          "Snow-Covered Mountain", "Snow-Covered Forest"}


def themes(raw):
    """Split explicit combinations, never infer a relationship from the separator."""
    parts = re.split(r"\s+(?:vs\.?|versus|and)\s+|\s*[×/]\s*", raw, flags=re.I)
    return [part.strip() for part in parts if part.strip()] or [raw]


def timeline_keys(markdown):
    """Existing editorial orders, with honest chronology qualifications."""
    info = {}
    for scope in ("postmending", "invasion", "omenpaths"):
        for index, row in enumerate(Q.timeline_view(markdown, scope)["rows"]):
            for cell in row["cells_markdown"]:
                for anchor in re.findall(r"Conflicts%20%26%20Arcs\.md#([\w-]+)", cell):
                    key = "Conflicts & Arcs.md#" + anchor
                    info.setdefault(key, {"scope": scope, "row_index": index,
                        "marker": row["marker"], "ordering_rule": Q.TIMELINE_METHODS[scope],
                        "official_sources": row["official_sources_on_row"]})
    return info


def beat_group(arc, time):
    eras = " ".join(arc.get("links", {}).get("eras", []))
    if "pre-mending--ancient" in eras:
        return "ancient"
    if "brothers-war--phyrexian-wars" in eras:
        return "brothers"
    if time:
        return time["scope"]
    if "phyrexian-invasion" in eras:
        return "invasion"
    if "omenpath-era-post-invasion" in eras:
        return "omenpaths"
    if "post-mending-gatewatch-era" in eras:
        return "postmending"
    return "unplaced"


def plan(theme, index, timeline, limit=18, entry_sources=None):
    """Collect directly linked arcs, then order only by existing era/row labels."""
    entry_sources = entry_sources or {}
    items = index["items"]
    by_id = {f"{e['page']}#{e['anchor']}": e for e in items}
    subjects, arcs = [], set()
    discovery = defaultdict(set)
    for term in themes(theme):
        hits = [e for e in items if e["name"].casefold() == term.casefold()]
        if not hits:
            hits = [e for e in items if term.casefold() in e["name"].casefold()]
        for e in hits[:8]:
            if e not in subjects:
                subjects.append(e)
            for key in e.get("links", {}).get("arcs", []):
                if key in by_id and by_id[key]["kind"] == "arc":
                    arcs.add(key)
                    discovery[key].add("curated_subject_arc_pointer")
            if e["kind"] == "arc":
                key = f"{e['page']}#{e['anchor']}"
                arcs.add(key)
                discovery[key].add("named_arc_itself")
    # A timeline row mentioning *all* requested subjects can surface an arc
    # omitted from the character index. This is contextual discovery only;
    # co-occurrence is never promoted to proof they met/fought.
    if len(themes(theme)) > 1:
        aliases = [term.split()[-1] if len(term.split()) > 1 else term for term in themes(theme)]
        for scope in ("postmending", "invasion", "omenpaths"):
            for row in Q.timeline_view(timeline, scope)["rows"]:
                content = " ".join(row["cells_markdown"])
                if not all(re.search(r"(?<!\w)" + re.escape(n) + r"(?!\w)", content, re.I) for n in aliases):
                    continue
                for anchor in re.findall(r"Conflicts%20%26%20Arcs\.md#([\w-]+)", content):
                    key = "Conflicts & Arcs.md#" + anchor
                    if key in by_id and by_id[key]["kind"] == "arc":
                        arcs.add(key)
                        discovery[key].add("same_timeline_row_mentions_requested_names_contextual_only")
    order = timeline_keys(timeline)
    beats = []
    for key in arcs:
        entry = by_id[key]
        timing = order.get(key)
        group = beat_group(entry, timing)
        source_urls = (entry_sources.get(key) or [])[:12]
        if timing:
            source_urls = sorted(set(source_urls + timing["official_sources"]))
        beats.append({"title": entry["name"], "lore_key": key,
            "discovery_evidence": sorted(discovery[key]),
            "narrative_group": group, "timeline": timing or {"scope": "unplaced", "ordering_rule": "no_verified_relative_sequence"},
            "official_sources": source_urls, "flags": entry.get("flags", {}),
            "card_page_links": entry.get("links", {}).get("cards", []),
            "enriched_candidates": entry.get("enriched_cards", []),
            "selection_note": "Use exact printing flavor, official story link, or labelled creative echo before assigning a slot."})
    beats.sort(key=lambda b: (ORDER.index(b["narrative_group"]), b["timeline"].get("row_index", 999), b["title"]))
    names = sorted({name for e in subjects for name in e.get("enriched_cards", [])})
    return {"theme": theme,
            "subjects": [{"name": e["name"], "key": f"{e['page']}#{e['anchor']}",
                           "flags": e.get("flags", {})} for e in subjects],
            "beats": beats[:limit], "beat_total": len(beats),
            "subject_card_alternatives": names[:70],
            "unplaced_or_ambiguous": [b["lore_key"] for b in beats if b["narrative_group"] == "unplaced"],
            "ordering_warning": "Groups are a creative reading sequence, not a globally proven event chronology. Omenpath row order is NOT a total time order.",
            "next_step": "Pick a legal commander and a selection of story cards, then assemble an explicit 100-card spec and run --validate."}


def assemble(spec, validator=None):
    """No silent fill-ins: card selection belongs to the user/story author."""
    commander = spec.get("commander", "").strip()
    if not commander:
        raise ValueError("commander required")
    beats = spec.get("beats", [])
    if not beats:
        raise ValueError("at least one story beat required")
    names, reasons, beat_summary = [commander], {}, []
    for beat in beats:
        if not beat.get("title") or not beat.get("lore_keys"):
            raise ValueError("every beat requires title and lore_keys")
        selected = []
        for card in beat.get("cards", []):
            name = card.get("name", "").strip()
            if not name or not card.get("why") or not card.get("evidence"):
                raise ValueError(f"beat {beat['title']}: every card needs name, why and evidence")
            if card["evidence"] == "direct_official" and not str(card.get("source", "")).startswith("https://magic.wizards.com/"):
                raise ValueError(f"{name}: direct_official needs an official Wizards source URL")
            names.append(name)
            reasons[name] = {"beat": beat["title"], "why": card["why"], "evidence": card["evidence"],
                             "source": card.get("source")}
            selected.append(name)
        beat_summary.append({"title": beat["title"], "lore_keys": beat["lore_keys"], "cards": selected})
    for card in spec.get("playability", []):
        name = card.get("name", "").strip()
        if not name or not card.get("why"):
            raise ValueError("every playability card needs name and why")
        names.append(name)
        reasons[name] = {"beat": "playability", "why": card["why"], "evidence": "guidance_not_story_proof"}
    basics = spec.get("basics", {})
    for name, qty in basics.items():
        if name not in BASICS or not isinstance(qty, int) or isinstance(qty, bool) or qty < 0:
            raise ValueError(f"invalid basic land count: {name}={qty}")
    nonbasic = names
    if len(set(nonbasic)) != len(nonbasic):
        raise ValueError("duplicate commander/nonbasic card name in proposed list")
    if any(name in BASICS for name in nonbasic):
        raise ValueError("put basic lands in basics, not story/playability slots")
    total = len(nonbasic) + sum(basics.values())
    lines = [f"1x {commander} [Commander]"] + [f"1x {n}" for n in names[1:]]
    lines += [f"{qty}x {name}" for name, qty in basics.items() if qty]
    text = "\n".join(lines) + "\n"
    result = {"theme": spec.get("theme"), "commander": commander, "total": total,
              "nonbasic_slots": len(nonbasic), "basic_slots": sum(basics.values()),
              "beats": beat_summary, "reasons": reasons, "decklist": text,
              "evidence_warning": "Story reasons/sources are author-supplied and must be checked against printing text and official citations before finalization; rule validation does not verify lore.",
              "validation": {"status": "not_run", "claim": "Not a confirmed legal Commander deck"}}
    if total != 100:
        result["validation"] = {"status": "incomplete", "count_delta": 100-total,
                                "claim": "Not a 100-card Commander deck"}
        return result
    if validator is not None:
        facts = validator(text)
        hard = [e for e in facts["issues"] if e["type"] in facts.get("hard_types", ())]
        result["validation"] = {"status": "passed" if not hard else "failed", "hard_issues": hard,
                                "count": facts["total"], "color_identity": facts.get("ci"),
                                "claim": "Validated against supplied current card data" if not hard else "Illegal or unresolved"}
        if "bracket_floor" in facts:
            result["validation"].update({"minimum_bracket_without_combo_audit": facts["bracket_floor"],
                "game_changers": facts.get("game_changers", []),
                "mass_land_denial": facts.get("mass_land_denial", []),
                "lands": facts.get("lands"),
                "bracket_note": "two-card infinite combos not yet independently checked"})
    return result


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="action", required=True)
    p = sub.add_parser("plan")
    p.add_argument("theme")
    p.add_argument("--limit", type=int, default=18)
    a = sub.add_parser("assemble")
    a.add_argument("spec", type=Path)
    a.add_argument("--validate", action="store_true")
    a.add_argument("--bulk-file", type=Path, default=None,
                   help="explicit local Scryfall JSONL/JSONL.gz for this lore test; does not alter the frozen Grixis lock")
    args = parser.parse_args(argv)
    try:
        if args.action == "plan":
            data = json.loads((ROOT / "data/lore_entries.json").read_text(encoding="utf-8"))
            time = (ROOT / "Master Timeline.md").read_text(encoding="utf-8")
            import lore_lib as L
            sources = {f"{e['page']}#{e['anchor']}": L.official_urls(e["text"]) for e in L.all_entries()}
            result = plan(args.theme, data, time, args.limit, sources)
        else:
            spec = json.loads(args.spec.read_text(encoding="utf-8"))
            validator = None
            if args.validate:
                import evaluate_decklist as ev
                try:
                    # The main Grixis work has a frozen snapshot lock. Testing
                    # a separate lore deck may name another explicit source,
                    # but must never rewrite, delete, or silently replace it.
                    original_get_bulk = ev.ing.get_bulk
                    if args.bulk_file:
                        source = args.bulk_file.resolve()
                        if not source.is_file():
                            parser.error(f"source not found: {source}")
                        def explicit_bulk(cache, unused, kind="oracle-cards"):
                            if kind == "oracle-cards":
                                return original_get_bulk(cache, str(source), kind)
                            return original_get_bulk(cache, unused, kind)
                        ev.ing.get_bulk = explicit_bulk
                    try:
                        R = ev.Resolver()
                    finally:
                        ev.ing.get_bulk = original_get_bulk
                except (OSError, IndexError) as exc:
                    parser.error(f"validation source unavailable: {exc}; cannot claim Commander legality")
                def validate_deck(deck):
                    d = ev.check(deck, R)
                    floor, gc, mld = ev.bracket_floor(d["cards"])
                    d.update(hard_types=ev.HARD, bracket_floor=floor,
                             game_changers=gc, mass_land_denial=mld,
                             lands=sum(x["qty"] for x in d["cards"]
                                       if "Land" in x["type"].split(" // ")[0].split("—")[0]))
                    return d
                validator = validate_deck
            result = assemble(spec, validator)
            if args.validate:
                result["validation"]["source"] = str(args.bulk_file.resolve()) if args.bulk_file else "repository frozen snapshot"
    except (OSError, ValueError) as exc:
        parser.error(str(exc))
    print(json.dumps(result, indent=2, ensure_ascii=False))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
