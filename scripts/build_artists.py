#!/usr/bin/env python3
"""Build the artist / art-credit index (issue #43, Bot cycle 13).

  data/artists.csv   one row per credited artist: distinct illustrations, printings, card entries,
                     first and latest year, top cards (by EDHREC rank)
  Artist Index.md    alphabetical index with letter sections, plus the most prolific artists
Source: Scryfall default-cards `artist` and `illustration_id` (every printing, paper and digital).
Joint credits ("A & B") count for each artist. Tokens, art-series and other non-card objects are excluded,
so only card entries are counted.
Usage: python3 scripts/build_artists.py && python3 scripts/resolve_card_links.py "Artist Index.md"
"""
import csv
import gzip
import json
import re
import sys
import unicodedata
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import ingest_scryfall as ing  # noqa: E402

CSV_OUT = ROOT / "data" / "artists.csv"
MD_OUT = ROOT / "Artist Index.md"


def letter(name):
    c = unicodedata.normalize("NFKD", name).encode("ascii", "ignore").decode()[:1].upper()
    return c if c.isalpha() else "#"


def main() -> int:
    index = {r["oracle_id"]: r for r in csv.DictReader((ROOT / "data" / "card_index.csv").open(encoding="utf-8"))}
    gz = sorted((ROOT / ".cache").glob("default-cards-*.jsonl.gz"))[-1]
    A = defaultdict(lambda: {"ill": set(), "pr": set(), "cards": set(), "years": set()})
    for ln in gzip.open(gz, "rt", encoding="utf-8"):
        c = json.loads(ln)
        o = c.get("oracle_id") or (c.get("card_faces") or [{}])[0].get("oracle_id")
        if o not in index:
            continue
        faces = c["card_faces"] if c.get("card_faces") and any("artist" in f for f in c["card_faces"]) else [c]
        for f in faces:
            art = f.get("artist") or c.get("artist")
            if not art:
                continue
            for a in re.split(r"\s+&\s+", art):
                a = a.strip()
                if not a or a.lower() == "unknown":
                    continue
                e = A[a]
                e["ill"].add(f.get("illustration_id") or c.get("illustration_id") or c["id"])
                e["pr"].add((c["set"], c["collector_number"], c.get("lang")))
                e["cards"].add(o)
                e["years"].add(c["released_at"][:4])
    rk = lambda o: (int(index[o]["edhrec_rank"]) if index[o]["edhrec_rank"] else 10**9, index[o]["name"])
    rows = []
    for a, e in A.items():
        top = sorted(e["cards"], key=rk)[:3]
        rows.append({"artist": a, "illustrations": len(e["ill"]), "printings": len(e["pr"]), "card_entries": len(e["cards"]),
                     "first_year": min(e["years"]), "latest_year": max(e["years"]),
                     "top_cards": "; ".join(index[o]["name"] for o in top)})
    rows.sort(key=lambda r: unicodedata.normalize("NFKD", r["artist"]).lower())
    with CSV_OUT.open("w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    letters = sorted({letter(r["artist"]) for r in rows}, key=lambda x: (x == "#", x))
    lab = lambda L: "Other" if L == "#" else L
    out = ["# Artist Index", "",
           "> **Bot cycle 13 · issue [#43](https://github.com/corymstover/GrokBotMTGCompanion/issues/43).** Every credited Magic artist on a card entry, with distinct illustrations, printings, card count, active years and their best-known cards (by EDHREC rank). Data: [`data/artists.csv`](data/artists.csv). Generated by `scripts/build_artists.py`.",
           f"> **Source:** Scryfall default-cards `artist` and `illustration_id` (bulk {gz.name.split('-')[2][:8]}), all printings and languages, card entries only (no tokens or art-series cards). A joint credit (\"A & B\") counts for both artists. Credits are spelled as Scryfall prints them, so one person can appear under two spellings ⚠️. Story context for art: [Art & Flavor Story Links](Art%20%26%20Flavor%20Story%20Links.md).",
           "", f"**Coverage:** {len(rows):,} artists · {sum(r['illustrations'] for r in rows):,} artist-illustration credits.", "",
           "## Contents", "- [Most prolific artists](#most-prolific-artists)", "- Alphabetical: " + " · ".join(f"[{lab(L)}](#{ing.gh_anchor('Artists ' + lab(L))})" for L in letters), "",
           "## Most prolific artists", "Top 40 by distinct illustrations.", "",
           "| Artist | Illustrations | Card entries | Years | Best-known cards |", "|---|---|---|---|---|"]
    fmt = lambda r: ", ".join(f"[[{n}]]" for n in r["top_cards"].split("; ") if n)
    esc = lambda s: s.replace("|", "\\|")
    for r in sorted(rows, key=lambda r: (-r["illustrations"], r["artist"]))[:40]:
        out.append(f"| {esc(r['artist'])} | {r['illustrations']} | {r['card_entries']} | {r['first_year']}–{r['latest_year']} | {fmt(r)} |")
    for L in letters:
        out += ["", f"## Artists {lab(L)}", "| Artist | Illustrations | Printings | Card entries | Years | Best-known cards |", "|---|---|---|---|---|---|"]
        for r in [r for r in rows if letter(r["artist"]) == L]:
            out.append(f"| {esc(r['artist'])} | {r['illustrations']} | {r['printings']} | {r['card_entries']} | {r['first_year']}–{r['latest_year']} | {fmt(r)} |")
    MD_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{CSV_OUT.name}: {len(rows)} artists")
    return 0


if __name__ == "__main__":
    sys.exit(main())
