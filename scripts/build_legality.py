#!/usr/bin/env python3
"""Build the format legality matrix (issue #41, Bot cycle 11).

  data/legality_matrix.csv   one row per card entry, one column per Scryfall format key.
                             Codes: L = legal, N = not legal, B = banned, R = restricted.
  Format Legality Matrix.md  per-format totals, full banned and restricted lists, and a lookup guide.
Source: Scryfall oracle-cards `legalities` (the same bulk that verify_cards.py checks).
Usage: python3 scripts/build_legality.py && python3 scripts/resolve_card_links.py "Format Legality Matrix.md"
"""
import atomic_io  # noqa: F401  atomic Path.write_text/write_bytes (Bot cycle 34)
import csv
import sys
from collections import Counter, defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import ingest_scryfall as ing  # noqa: E402

CSV_OUT = ROOT / "data" / "legality_matrix.csv"
MD_OUT = ROOT / "Format Legality Matrix.md"
CODE = {"legal": "L", "not_legal": "N", "banned": "B", "restricted": "R"}
ORDER = ["standard", "pioneer", "modern", "legacy", "vintage", "pauper", "commander", "oathbreaker",
         "brawl", "standardbrawl", "competitivebrawl", "paupercommander", "duel", "predh", "premodern",
         "oldschool", "penny", "gladiator", "historic", "timeless", "alchemy", "future", "tlr"]


def main() -> int:
    index = {r["oracle_id"]: r for r in csv.DictReader((ROOT / "data" / "card_index.csv").open(encoding="utf-8"))}
    cards, bulk = ing.get_bulk(ing.DEFAULT_CACHE, None)
    rows = []
    fmts = None
    for c in cards:
        if c.get("oracle_id") not in index:
            continue
        lg = c.get("legalities", {})
        if fmts is None:
            fmts = [f for f in ORDER if f in lg] + sorted(f for f in lg if f not in ORDER)
        rows.append((index[c["oracle_id"]]["name"], c["oracle_id"], {f: CODE.get(lg.get(f, "not_legal"), "N") for f in fmts}))
    rows.sort(key=lambda r: r[0].lower())
    with atomic_io.atomic_open(CSV_OUT, "w", newline="", encoding="utf-8") as fh:
        w = csv.writer(fh)
        w.writerow(["name", "oracle_id"] + fmts)
        for n, o, m in rows:
            w.writerow([n, o] + [m[f] for f in fmts])
    tot = {f: Counter(m[f] for _, _, m in rows) for f in fmts}
    lists = defaultdict(lambda: defaultdict(list))
    for n, _, m in rows:
        for f in fmts:
            if m[f] in "BR":
                lists[f][m[f]].append(n)
    out = ["# Format Legality Matrix", "",
           "> **Bot cycle 11 · issue [#41](https://github.com/corymstover/GrokBotMTGCompanion/issues/41).** Legality of every card entry in every format Scryfall tracks, beyond Commander. The full matrix is [`data/legality_matrix.csv`](data/legality_matrix.csv) (codes **L** legal · **N** not legal · **B** banned · **R** restricted). This page gives totals and the complete banned/restricted lists. Generated by `scripts/build_legality.py`.",
           f"> **Source:** Scryfall oracle-cards `legalities` (bulk `{bulk}`). For Wizards-run formats the official source is the [Banned and Restricted list](https://magic.wizards.com/en/banned-restricted-list); Scryfall follows it, and the maintenance cycle refreshes the bulk after each announcement ([#17](https://github.com/corymstover/GrokBotMTGCompanion/issues/17)). Several keys (e.g. `predh`, `premodern`, `oldschool`, `penny`, `gladiator`, `duel`) are formats with their own rules committees or definitions. This page does not say which body governs each one ⚠️. `future` is Scryfall's \"Future Standard\" key ([Scryfall syntax docs](https://scryfall.com/docs/syntax)).",
           "> **Commander note:** card legality is only half of Commander deck legality. Color identity and singleton rules still apply ([EDH Standards](EDH%20Standards.md)).", "",
           "## Contents", "- [Totals by format](#totals-by-format)", "- [Banned and restricted lists](#banned-and-restricted-lists)",
           *[f"  - [{f}](#{f})" for f in fmts if lists[f]], "- [Lookup](#lookup)", "",
           "## Totals by format", "| Format key | Legal | Banned | Restricted | Not legal |", "|---|---|---|---|---|"]
    for f in fmts:
        t = tot[f]
        out.append(f"| `{f}` | {t['L']:,} | {t['B']:,} | {t['R']:,} | {t['N']:,} |")
    out += ["", "## Banned and restricted lists", "Every card entry Scryfall marks banned or restricted, by format (alphabetical).", ""]
    for f in fmts:
        if not lists[f]:
            continue
        out.append(f"### {f}\n")
        for code, label in (("B", "Banned"), ("R", "Restricted")):
            if lists[f][code]:
                out.append(f"**{label} ({len(lists[f][code])}):** " + " · ".join(f"[[{n}]]" for n in sorted(lists[f][code], key=str.lower)) + "\n")
    out += ["## Lookup",
            "- **One card:** search `data/legality_matrix.csv` by name, e.g. `rg -i '^\"?Sol Ring' data/legality_matrix.csv`. Each card entry also shows its Commander legality.",
            "- **A whole format:** `python3 -c \"import csv;print(sum(r['modern']=='L' for r in csv.DictReader(open('data/legality_matrix.csv'))))\"`.",
            "- **Before recommending a card for a format:** check this matrix, then (for Commander) the color-identity rules in [EDH Standards](EDH%20Standards.md)."]
    MD_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{CSV_OUT.name}: {len(rows)} rows x {len(fmts)} formats; B/R lists in {sum(1 for f in fmts if lists[f])} formats, {sum(len(v) for f in fmts for v in lists[f].values())} entries")
    return 0


if __name__ == "__main__":
    sys.exit(main())
