#!/usr/bin/env python3
"""Append a factual "Commander rules & rulings" block to each deck skeleton.

For every decks/*.md file this writes (between RULES-NOTES markers):
  * the commander's Oracle text, verbatim from Scryfall Oracle bulk;
  * every official ruling on the commander (Scryfall rulings bulk, joined by oracle_id);
  * creature-type overlap with the commander (count + examples) — a factual tribal hint;
  * the deck cards that carry official rulings (linked to their card entries).
No opinions are generated; synergy judgments stay in EDH Standards, labeled Opinion.
Usage: python3 scripts/deck_rules_notes.py [deck.md ...]
"""
import csv
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import ingest_scryfall as ing  # noqa: E402

ROOT = ing.ROOT
START, END = "<!-- RULES-NOTES:START -->", "<!-- RULES-NOTES:END -->"


def main(argv):
    cards, bulk_date = ing.get_bulk(ing.DEFAULT_CACHE, None)
    rulings, rdate = ing.get_bulk(ing.DEFAULT_CACHE, None, kind="rulings")
    by_oid = {}
    for r in rulings:
        by_oid.setdefault(r["oracle_id"], []).append(r)
    idx = {r["name"]: r for r in csv.DictReader(open(ROOT / "data/card_index.csv"))}
    oracle = {c["name"]: c for c in cards if c["name"] in idx}
    decks = [Path(a) for a in argv] or sorted((ROOT / "decks").glob("*.md"))
    for p in decks:
        t = p.read_text()
        m = re.search(r"^1x (.+?) \[Commander", t, re.M)
        if not m:
            print("no commander:", p); continue
        cmd = m.group(1)
        names = [n for n in re.findall(r"^1x (.+?) \[", t, re.M)][1:]
        c = oracle[cmd]
        faces = c.get("card_faces") or [c]
        L = [START, "## Commander rules & rulings", "",
             f"> Auto-generated by `scripts/deck_rules_notes.py` from Scryfall Oracle bulk ({bulk_date[:10]}) and rulings bulk ({rdate[:10]}); rulings are quoted verbatim (source: Wizards of the Coast unless marked). Facts only — strategy is in [EDH Standards](../EDH%20Standards.md#synergy-notes), labeled Opinion.", ""]
        L.append(f"**Oracle text — {ing.link(idx[cmd], '../')}:**")
        for f in faces:
            txt = (f.get("oracle_text") or "").replace("\n", " / ")
            L.append(f"> {f.get('name', cmd)}: {txt}")
        L.append("")
        rs = sorted(by_oid.get(c["oracle_id"], []), key=lambda r: r["published_at"])
        if rs:
            L.append(f"**Official rulings on the commander ({len(rs)}):**")
            for r in rs:
                src = "" if r["source"] == "wotc" else " *(Scryfall note)*"
                L.append(f"- *{r['published_at']}*{src} — {ing.ruling_text(r)}")
        else:
            L.append("**Official rulings on the commander:** none published on Scryfall.")
        L.append("")
        sub = set()
        for f in faces:
            tl = f.get("type_line", "")
            if "Creature" in tl and "—" in tl:
                sub |= set(tl.split("—", 1)[1].split())
        if sub:
            share = [n for n in names if n in oracle and "Creature" in oracle[n].get("type_line", "") and
                     sub & set(oracle[n].get("type_line", "").split("—", 1)[-1].split())]
            L.append(f"**Creature-type overlap** with the commander ({', '.join(sorted(sub))}): {len(share)} card(s)" +
                     (" — " + ", ".join(ing.link(idx[n], '../') for n in share[:12]) + (" …" if len(share) > 12 else "") if share else "") + ".")
            L.append("")
        withr = [(n, len(by_oid.get(oracle[n]["oracle_id"], []))) for n in names if n in oracle]
        withr = [x for x in withr if x[1]]
        L.append(f"**Deck cards with official rulings:** {len(withr)} of {len(names)} non-basic cards — " +
                 ", ".join(f"{ing.link(idx[n], '../')} ({k})" for n, k in withr) + ".")
        L.append(END)
        block = "\n".join(L)
        if START in t:
            t = re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: block, t, flags=re.S)
        else:
            t = t.rstrip("\n") + "\n\n" + block + "\n"
        if "- [Commander rules & rulings]" not in t:
            t = t.replace("- [Rejected candidates](#rejected-candidates)", "- [Rejected candidates](#rejected-candidates)\n- [Commander rules & rulings](#commander-rules--rulings)", 1)
        p.write_text(t)
        print(f"{p.name}: {len(rs)} commander rulings, {len(withr)} cards with rulings")


if __name__ == "__main__":
    main(sys.argv[1:])
