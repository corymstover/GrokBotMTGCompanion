#!/usr/bin/env python3
"""Build structured token, emblem and dungeon data (issue #42, Bot cycle 12).

These are NOT cards: none of them can be put in a deck (CR 111.1, 114.1, 309.2).
  data/tokens.json                    every Scryfall token / double_faced_token / emblem / dungeon object:
                                      name, kind, type line, colors, P/T, Oracle text, keywords, and which card
                                      entries create it (from Scryfall `all_parts`)
  Tokens, Emblems & Dungeons.md       readable tables, plus the adventurer cards (real cards, CR 715)
Usage: python3 scripts/build_tokens.py && python3 scripts/resolve_card_links.py "Tokens, Emblems & Dungeons.md"
"""
import atomic_io  # noqa: F401  atomic Path.write_text/write_bytes (Bot cycle 34)
import csv
import gzip
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
import ingest_scryfall as ing  # noqa: E402

JSON_OUT = ROOT / "data" / "tokens.json"
MD_OUT = ROOT / "Tokens, Emblems & Dungeons.md"


def kind(c):
    first = c.get("type_line", "").split(" // ")[0]
    if first.startswith("Dungeon"):
        return "dungeon"
    if c["layout"] == "emblem":
        return "emblem"
    if c["layout"] in ("token", "double_faced_token"):
        return "token"
    return None


def text_of(c):
    if c.get("card_faces"):
        return " // ".join(f"{f.get('name')}: {f.get('oracle_text', '')}" for f in c["card_faces"])
    return c.get("oracle_text", "")


def cr(lines, num):
    for l in lines:
        if l.startswith(num + " "):
            return l[len(num) + 1:]
    return ""


def esc(s):
    return s.replace("|", "\\|").replace("\n", " ").replace("<", "&lt;").replace("[[", "[ [")


def main() -> int:
    index = {r["oracle_id"]: r for r in csv.DictReader((ROOT / "data" / "card_index.csv").open(encoding="utf-8"))}
    cards, bulk = ing.get_bulk(ing.DEFAULT_CACHE, None)
    objs = {c["oracle_id"]: c for c in cards if c.get("oracle_id") and kind(c) and c.get("set") != "phtr" and c.get("set_type") not in ("memorabilia", "minigame")}
    gz = sorted((ROOT / ".cache").glob("default-cards-*.jsonl.gz"))[-1]
    id2o = {}
    makers = defaultdict(set)
    for ln in gzip.open(gz, "rt", encoding="utf-8"):
        c = json.loads(ln)
        o = c.get("oracle_id") or (c.get("card_faces") or [{}])[0].get("oracle_id")
        id2o[c["id"]] = o
        if o in index:
            for p in c.get("all_parts", []):
                if p.get("component") == "token" or p.get("type_line", "").startswith(("Emblem", "Dungeon")):
                    makers[p["id"]].add(o)
    made = defaultdict(set)
    for pid, os_ in makers.items():
        to = id2o.get(pid)
        if to in objs:
            made[to] |= os_
    data = []
    for o, c in objs.items():
        mk = sorted(made.get(o, ()), key=lambda x: (int(index[x]["edhrec_rank"]) if index[x]["edhrec_rank"] else 10**9, index[x]["name"]))
        data.append({
            "name": c["name"], "oracle_id": o, "kind": kind(c), "layout": c["layout"], "type_line": c.get("type_line", ""),
            "colors": c.get("colors", (c.get("card_faces") or [{}])[0].get("colors", [])), "power": c.get("power"), "toughness": c.get("toughness"),
            "oracle_text": text_of(c), "keywords": c.get("keywords", []), "set": c["set"].upper(),
            "created_by": [index[x]["name"] for x in mk], "is_card": False,
        })
    data.sort(key=lambda d: (d["kind"], d["name"].lower(), d["type_line"], d["power"] or "", d["oracle_text"]))
    JSON_OUT.write_text(json.dumps({"source": f"Scryfall oracle-cards {bulk}", "note": "NOT cards: tokens, emblems and dungeons cannot be included in a deck (CR 111.1, 114.1, 309.2).", "objects": data}, ensure_ascii=False, indent=1), encoding="utf-8")
    lines = sorted((ROOT / ".cache").glob("MagicCompRules-*.txt"))[-1].read_text(encoding="utf-8-sig").splitlines()
    by = defaultdict(list)
    for d in data:
        sub = d["kind"]
        if sub == "token":
            sub = "creature" if "Creature" in d["type_line"] else "noncreature"
        by[sub].append(d)

    def mk(d, n=3):
        if not d["created_by"]:
            return "❓ no card entry links it"
        extra = f" +{len(d['created_by']) - n} more" if len(d["created_by"]) > n else ""
        return ", ".join(f"[[{x}]]" for x in d["created_by"][:n]) + extra

    col = lambda d: "".join(d["colors"]) or "C"
    adv = sorted(index[c["oracle_id"]]["name"] for c in cards if c.get("layout") == "adventure" and c.get("oracle_id") in index)
    out = ["# Tokens, Emblems & Dungeons", "",
           "> 🚫 **NOT CARDS.** Nothing listed in the first four sections can go in a deck or count toward a Commander deck's 100 cards. They are game objects that cards **create** or **bring in from outside the game**. Generated by `scripts/build_tokens.py`. Structured data: [`data/tokens.json`](data/tokens.json) (`is_card: false`).",
           f"> **Source:** Scryfall oracle-cards (bulk `{bulk}`), layouts `token`, `double_faced_token` and `emblem`, plus type line `Dungeon` (Scryfall's memorabilia, minigame and playtest sets excluded). \"Created by\" comes from Scryfall `all_parts` links on card entries, ordered by EDHREC rank. Bot cycle 12 · issue [#42](https://github.com/corymstover/GrokBotMTGCompanion/issues/42).",
           "",
           f"> **CR 111.1** {cr(lines, '111.1.')}",
           f"> **CR 114.1** {cr(lines, '114.1.')}",
           f"> **CR 309.2** {cr(lines, '309.2.')}",
           "",
           f"**Counts:** {len(by['creature'])} creature tokens · {len(by['noncreature'])} noncreature tokens · {len(by['emblem'])} emblems · {len(by['dungeon'])} dungeons · {len(adv)} adventurer cards (real cards).",
           "", "## Contents", "- [Creature tokens](#creature-tokens)", "- [Noncreature tokens](#noncreature-tokens)", "- [Emblems](#emblems)", "- [Dungeons](#dungeons)", "- [Adventurer cards (real cards)](#adventurer-cards-real-cards)", "",
           "## Creature tokens", "Different tokens with the same name (e.g. many \"Soldier\" tokens) are separate rows: they differ in color, P/T or abilities.", "",
           "| Token | Type line | P/T | Color | Abilities | Created by |", "|---|---|---|---|---|---|"]
    for d in by["creature"]:
        out.append(f"| {esc(d['name'])} | {esc(d['type_line'])} | {d['power'] or '—'}/{d['toughness'] or '—'} | {col(d)} | {esc(d['oracle_text']) or '—'} | {mk(d)} |")
    out += ["", "## Noncreature tokens", "| Token | Type line | Color | Text | Created by |", "|---|---|---|---|---|"]
    for d in by["noncreature"]:
        out.append(f"| {esc(d['name'])} | {esc(d['type_line'])} | {col(d)} | {esc(d['oracle_text']) or '—'} | {mk(d)} |")
    out += ["", "## Emblems", f"> **CR 114.4** {cr(lines, '114.4.')} \"Created by\" is usually the planeswalker whose ability makes it.", "",
            "| Emblem | Text | Created by |", "|---|---|---|"]
    for d in by["emblem"]:
        out.append(f"| {esc(d['name'])} | {esc(d['oracle_text'])} | {mk(d)} |")
    out += ["", "## Dungeons", f"> **CR 309.1** {cr(lines, '309.1.')} Enter one with *venture into the dungeon* (CR 701.49) or the initiative, which \"ventures into Undercity\" (CR 726, Glossary).", "",
            "| Dungeon | Rooms (Oracle text) | Brought in by (examples) |", "|---|---|---|"]
    for d in by["dungeon"]:
        out.append(f"| {esc(d['name'])} | {esc(d['oracle_text'])} | {mk(d, 5)} |")
    out += ["", "## Adventurer cards (real cards)",
            f"> These **are** cards (CR 715). **CR 715.1** {cr(lines, '715.1.')} **CR 715.2c** {cr(lines, '715.2c')}", "",
            " · ".join(f"[[{n}]]" for n in adv)]
    MD_OUT.write_text("\n".join(out) + "\n", encoding="utf-8")
    print(f"{JSON_OUT.name}: {len(data)} objects; " + ", ".join(f"{k} {len(v)}" for k, v in by.items()) + f"; adventure {len(adv)}; with makers {sum(1 for d in data if d['created_by'])}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
